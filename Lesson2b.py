# Arithmetic operators
# +, -, *, /
# Modulus (%) -- It is used to show the remainder when a number subdivides another number
modulus = 25 % 7
print(modulus)

# floor division (//) -- It is the number of times a certain number divides another ignoring the remainder.
floor = 25 // 7
print(floor)

# exponent (**) -- It is the power factor
exponent = 10 ** 3
print(exponent)


# Comparison/relational operators -- they are used to compare two or more values/expressions/equations. >, <, >=, <=, ==, != . They result into a True/False answer
print(5 > 2)
print(5 < 2)
print(5 >= 2)
print(5 <= 2)
print(5 == 2)
print(5 != 2)
